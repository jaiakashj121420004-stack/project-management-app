// --- Recurrences --------------------------------------------------------
// User-global (not per-day) — every active rule is evaluated client-side
// against whichever day is being viewed. See recurrence.ts for the rule
// shapes and ruleMatchesDate().

/** All of the signed-in user's active recurrence templates. */
export async function fetchRecurrences(): Promise<TodoRecurrence[]> {
  const { data, error } = await supabase
    .from('todo_recurrences')
    .select('*')
    .eq('active', true)
    .order('created_at', { ascending: true });
  if (error) throw error;
  return data;
}

export async function insertRecurrence(input: {
  name: string;
  items: string[];
  rule: RecurrenceRule;
}): Promise<TodoRecurrence> {
  const { data, error } = await supabase
    .from('todo_recurrences')
    .insert({ name: input.name, items: input.items, rule: input.rule })
    .select('*')
    .single();
  if (error) throw error;
  return data;
}

export async function updateRecurrence(
  id: string,
  patch: { name?: string; items?: string[]; rule?: RecurrenceRule },
): Promise<TodoRecurrence> {
  const { data, error } = await supabase
    .from('todo_recurrences')
    .update(patch)
    .eq('id', id)
    .select('*')
    .single();
  if (error) throw error;
  return data;
}

/** Deleting a recurrence stops future regeneration; already-created lists
 *  stay put (their `source_recurrence_id` just goes null via ON DELETE SET NULL). */
export async function removeRecurrence(id: string): Promise<void> {
  const { error } = await supabase.from('todo_recurrences').delete().eq('id', id);
  if (error) throw error;
}
